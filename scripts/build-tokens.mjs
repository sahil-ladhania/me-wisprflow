// Turns design-system/tokens.json into the CSS and TypeScript the app uses.
// Run `pnpm tokens` after changing tokens.json; the three outputs are committed.
//
//   app/styles/tokens.css      every token as a CSS variable (day + night) and its Tailwind theme entry
//   app/styles/typography.css  the 14 type styles as Tailwind utilities (type-display, type-kicker, ...)
//   lib/design-system/tokens.ts the same values, typed, for components that need them in JS

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "design-system/tokens.json"), "utf8"));

// The design system switches from phone to tablet sizes at 600px.
const BREAKPOINT = "37.5rem";

// next/font self-hosts each family and exposes it as a CSS variable (see app/fonts.ts).
// The first family in each token stack is the Google font, so it is swapped for that variable.
const NEXT_FONT_VARS = { story: "--font-newsreader", road: "--font-barlow-condensed", hand: "--font-kalam" };

// Barlow Condensed has no ₹. A face limited to U+20B9 goes in front of it, so it is used for ₹ and
// skipped for everything else (see roadRupee in app/fonts.ts; app/layout.tsx sets the variable).
// The fallback keeps the stack valid if the variable is ever missing.
const GLYPH_FACES = { road: ['var(--font-road-rupee, "Barlow Condensed")'] };

// Shadows that change in the night theme get hand-made utilities (see below), so they stay out of @theme.
const SHADOW_UTILITIES = ["shadow-contact", "shadow-lift", "shadow-ground"];

const banner = (what) =>
  [
    "/*",
    ` * The Ride: ${what}.`,
    " * Generated by scripts/build-tokens.mjs from design-system/tokens.json.",
    " * Do not edit by hand: change the JSON and run `pnpm tokens`.",
    " */",
    "",
  ].join("\n");

const valueFor = (value, theme) => (typeof value === "string" ? value : value[theme]);
const isThemed = (value) => typeof value === "object" && value !== null;

function fontStack(key) {
  const [first, ...rest] = tokens.type.families[key].split(",").map((part) => part.trim());
  return [...(GLYPH_FACES[key] ?? []), `var(${NEXT_FONT_VARS[key]}, ${first})`, ...rest].join(", ");
}

const colors = tokens.color.tokens;
const shadows = tokens.shadow.tokens;
const spacing = tokens.spacing.tokens;
const radii = tokens.radius.tokens;
const layout = tokens.layout.tokens;
const timing = tokens.timing.tokens;
const durations = timing.filter((t) => t.name.startsWith("dur-"));
const easings = timing.filter((t) => t.name.startsWith("ease-"));

// ---------- app/styles/tokens.css ----------

function tokensCss() {
  const out = [banner("design tokens")];

  out.push(
    "/* Tokens whose names already are Tailwind theme names. Tailwind emits them as CSS variables",
    "   on :root and builds utilities from them: font-story, rounded-stone, ease-brake, p-5, max-w-measure.",
    "   Spacing keys 1–10 are the design system's space-1…space-10, so p-5 is 24px here, not Tailwind's 20px. */",
    "@theme static {",
  );
  for (const key of Object.keys(tokens.type.families)) out.push(`  --font-${key}: ${fontStack(key)};`);
  out.push("");
  for (const t of radii) out.push(`  --${t.name}: ${t.value};`);
  out.push("");
  for (const t of easings) out.push(`  --${t.name}: ${t.value};`);
  out.push("");
  for (const t of spacing) out.push(`  --spacing-${t.name.replace("space-", "")}: ${t.value};`);
  out.push("");
  out.push(`  --container-measure: ${layout.find((t) => t.name === "measure").value};`);
  out.push(`  --container-page: ${layout.find((t) => t.name === "page-max").value};`);
  out.push("}", "");

  out.push(
    "/* Colours. Utilities point straight at the raw token (bg-paper → var(--paper)),",
    "   so a [data-theme=\"night\"] scope re-colours everything inside it. */",
    "@theme inline {",
  );
  for (const t of colors) out.push(`  --color-${t.name}: var(--${t.name});`);
  out.push("}", "");

  out.push("/* Shadow utilities read the raw token for the same reason. */");
  for (const name of SHADOW_UTILITIES) out.push(`@utility ${name} {\n  box-shadow: var(--${name});\n}`);
  out.push("");

  out.push(':root,\n[data-theme="day"] {');
  out.push("  /* colour */");
  for (const t of colors) out.push(`  --${t.name}: ${valueFor(t.value, "day")};`);
  out.push("", "  /* spacing */");
  for (const t of spacing) out.push(`  --${t.name}: ${t.value};`);
  out.push("", "  /* shadow */");
  for (const t of shadows) out.push(`  --${t.name}: ${valueFor(t.value, "day")};`);
  out.push("", "  /* layout */");
  for (const t of layout) out.push(`  --${t.name}: ${t.value};`);
  out.push("", "  /* timing */");
  for (const t of durations) out.push(`  --${t.name}: ${t.value};`);
  out.push("}", "");

  out.push(
    "/* Night is not a dark mode. It is applied with data-theme=\"night\" to the June 2025 stop",
    "   (and the lane while the reader is there), and every themed token swaps underneath it. */",
    '[data-theme="night"] {',
    "  color-scheme: dark;",
  );
  for (const t of colors) if (isThemed(t.value)) out.push(`  --${t.name}: ${t.value.night};`);
  for (const t of shadows) if (isThemed(t.value)) out.push(`  --${t.name}: ${t.value.night};`);
  out.push("}", "");

  return out.join("\n");
}

// ---------- app/styles/typography.css ----------

function typographyCss() {
  const out = [banner("type styles")];
  out.push(
    "/* One utility per type style, mobile size first, desktop size from 600px.",
    "   Usage notes are copied from tokens.json. */",
    "",
  );
  for (const group of tokens.type.groups) {
    out.push(`/* ${group.name} */`, "");
    for (const style of group.styles) {
      const mobile = /Mobile:\s*(\d+)px/.exec(style.usage)?.[1];
      const colour = /Colour ([a-z-]+)\./.exec(style.usage)?.[1];
      const lines = [
        `  font-family: var(--font-${group.family});`,
        `  font-size: ${mobile ? `${mobile}px` : style.fontSize};`,
        `  line-height: ${style.lineHeight};`,
        `  font-weight: ${style.fontWeight};`,
      ];
      if (style.letterSpacing) lines.push(`  letter-spacing: ${style.letterSpacing};`);
      if (style.fontStyle) lines.push(`  font-style: ${style.fontStyle};`);
      if (/uppercase/i.test(style.usage)) lines.push("  text-transform: uppercase;");
      if (group.family === "road") lines.push("  font-variant-numeric: tabular-nums;");
      if (colour) lines.push(`  color: var(--${colour});`);
      if (mobile && `${mobile}px` !== style.fontSize) {
        lines.push(`  @media (width >= ${BREAKPOINT}) {`, `    font-size: ${style.fontSize};`, "  }");
      }
      out.push(`/* ${style.usage} */`, `@utility type-${style.name} {`, ...lines, "}", "");
    }
  }
  return out.join("\n");
}

// ---------- lib/design-system/tokens.ts ----------

function tokensTs() {
  const ms = (value) => Number.parseFloat(value);
  const px = (value) => Number.parseFloat(value);
  const strip = (name, prefix) => name.replace(prefix, "");

  const data = {
    colors: Object.fromEntries(colors.map((t) => [t.name, { day: valueFor(t.value, "day"), night: valueFor(t.value, "night"), usage: t.usage }])),
    fonts: tokens.type.families,
    typeStyles: Object.fromEntries(
      tokens.type.groups.flatMap((group) =>
        group.styles.map((s) => {
          const mobile = /Mobile:\s*(\d+)px/.exec(s.usage)?.[1];
          return [
            s.name,
            {
              family: group.family,
              fontSize: px(s.fontSize),
              mobileFontSize: mobile ? Number(mobile) : px(s.fontSize),
              lineHeight: s.lineHeight,
              fontWeight: s.fontWeight,
              letterSpacing: s.letterSpacing ?? null,
              fontStyle: s.fontStyle ?? "normal",
              sample: s.sample,
              usage: s.usage,
            },
          ];
        }),
      ),
    ),
    space: Object.fromEntries(spacing.map((t) => [strip(t.name, "space-"), px(t.value)])),
    radius: Object.fromEntries(radii.map((t) => [strip(t.name, "radius-"), t.value])),
    shadows: Object.fromEntries(shadows.map((t) => [t.name, { day: valueFor(t.value, "day"), night: valueFor(t.value, "night") }])),
    layout: Object.fromEntries(layout.map((t) => [t.name, t.value])),
    durations: Object.fromEntries(durations.map((t) => [strip(t.name, "dur-"), ms(t.value)])),
    easings: Object.fromEntries(easings.map((t) => [strip(t.name, "ease-"), t.value])),
  };

  const out = [
    "// The Ride: design tokens for TypeScript.",
    "// Generated by scripts/build-tokens.mjs from design-system/tokens.json.",
    "// Do not edit by hand: change the JSON and run `pnpm tokens`.",
    "",
    'export const themes = ["day", "night"] as const;',
    "export type Theme = (typeof themes)[number];",
    "",
    "/** Width in px where the design system switches from phone to tablet sizes (Tailwind's `sm:`). */",
    "export const breakpoint = 600;",
    "",
  ];
  for (const [key, value] of Object.entries(data)) {
    out.push(`export const ${key} = ${JSON.stringify(value, null, 2)} as const;`, "");
  }
  out.push(
    "export type ColorName = keyof typeof colors;",
    "export type TypeStyleName = keyof typeof typeStyles;",
    "export type DurationName = keyof typeof durations;",
    "export type EasingName = keyof typeof easings;",
    "",
    "/** A colour token's value in one theme. */",
    'export function color(name: ColorName, theme: Theme = "day"): string {',
    "  return colors[name][theme];",
    "}",
    "",
  );
  return out.join("\n");
}

function write(relative, contents) {
  const path = resolve(root, relative);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`wrote ${relative}`);
}

write("app/styles/tokens.css", tokensCss());
write("app/styles/typography.css", typographyCss());
write("lib/design-system/tokens.ts", tokensTs());
